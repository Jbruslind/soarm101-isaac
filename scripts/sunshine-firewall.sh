#!/usr/bin/env bash
# Restrict the Sunshine ports (web UI + Moonlight streaming) to LAN/VPN clients.
#
# Sunshine itself has no source-address filter for its streaming ports, so this
# installs a dedicated nftables table that drops traffic to them from any source
# outside SUNSHINE_ALLOWED_SUBNETS (docker/.env). Other ports and existing
# ufw/nftables rules are left untouched. A systemd unit reapplies it at boot.
#
# Usage (needs root):
#   sudo ./scripts/sunshine-firewall.sh install   # write rules + enable at boot
#   sudo ./scripts/sunshine-firewall.sh remove
#   sudo ./scripts/sunshine-firewall.sh status
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
RULES=/etc/soarm/sunshine-fw.nft
UNIT=/etc/systemd/system/soarm-sunshine-fw.service
TABLE="inet soarm_sunshine"

[[ $EUID -eq 0 ]] || { echo "Run with sudo." >&2; exit 1; }

subnets() {
    local v=""
    [[ -f "$PROJECT_DIR/docker/.env" ]] && v="$(sed -n 's/^SUNSHINE_ALLOWED_SUBNETS=//p' "$PROJECT_DIR/docker/.env" | tail -1)"
    if [[ -z "$v" ]]; then
        echo "Set SUNSHINE_ALLOWED_SUBNETS in docker/.env (e.g. 192.168.1.0/24,10.0.0.0/24)." >&2
        exit 1
    fi
    echo "$v"
}

case "${1:-}" in
    install)
        allowed="$(subnets | tr -d ' ')"
        mkdir -p "$(dirname "$RULES")"
        cat > "$RULES" <<EOF
# Generated by soarm101-isaac/scripts/sunshine-firewall.sh — do not edit by hand.
table $TABLE
delete table $TABLE
table $TABLE {
    set allowed_v4 {
        type ipv4_addr
        flags interval
        elements = { 127.0.0.0/8, ${allowed//,/, } }
    }
    chain input {
        type filter hook input priority filter - 10; policy accept;
        iif "lo" accept
        tcp dport { 47984, 47989, 47990, 48010 } ip saddr != @allowed_v4 drop
        udp dport 47998-48000 ip saddr != @allowed_v4 drop
        meta nfproto ipv6 tcp dport { 47984, 47989, 47990, 48010 } drop
        meta nfproto ipv6 udp dport 47998-48000 drop
    }
}
EOF
        cat > "$UNIT" <<EOF
[Unit]
Description=SO-ARM Sunshine: restrict streaming ports to LAN/VPN
After=network-pre.target
Wants=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $RULES
ExecStop=/usr/sbin/nft delete table $TABLE

[Install]
WantedBy=multi-user.target
EOF
        systemctl daemon-reload
        systemctl enable soarm-sunshine-fw.service >/dev/null
        systemctl restart soarm-sunshine-fw.service
        echo "Sunshine ports now accept only: $allowed (plus localhost)."
        ;;
    remove)
        systemctl disable --now soarm-sunshine-fw.service 2>/dev/null || true
        rm -f "$UNIT" "$RULES"
        systemctl daemon-reload
        echo "Removed Sunshine firewall rules."
        ;;
    status)
        systemctl is-active soarm-sunshine-fw.service || true
        nft list table $TABLE 2>/dev/null || echo "table $TABLE not loaded"
        ;;
    *)
        sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
        exit 1
        ;;
esac
